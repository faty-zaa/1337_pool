#include <unistd.h>

void	ft_putnbr(int nb)
{
	long	n;
	char	c[12];
	int		i;

	n = nb;
	if (n == 0)
	{
		write(1, "0", 1);
		return ;
	}
	if (n < 0)
	{
		write(1, "-", 1);
		n *= -1;
	}
	i = 0;
	while (n > 0)
	{
		c[i] = (n % 10) + '0';
		n /= 10;
		i++;
	}
	while (i > 0)
		write(1, &c[--i], 1);
}
