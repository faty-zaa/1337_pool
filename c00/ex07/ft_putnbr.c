#include <unistd.h>

void	ft_putnbr(int nb)
{
	int		i;
	long	n;
	char	str[12];

	if (nb == 0)
	{
		write(1, "0", 1);
		return ;
	}
	n = nb;
	if (n < 0)
	{
		write(1, "-", 1);
		n *= -1;
	}
	i = 0;
	while (n > 0)
	{
		str[i++] = (n % 10) + '0';
		n /= 10;
	}
	while (i > 0)
		write (1, &str[--i], 1);
}
