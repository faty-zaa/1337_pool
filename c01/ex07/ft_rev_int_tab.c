void	ft_rev_int_tab(int *tab, int size)
{
	int	i;
	int	j;
	int	n;

	i = 0;
	j = size - 1;
	while (i < size / 2)
	{
		n = tab[j];
		tab[j] = tab[i];
		tab[i] = n;
		i++;
		j--;
	}
}
