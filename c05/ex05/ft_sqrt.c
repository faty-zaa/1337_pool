int	ft_sqrt(int nb)
{
	int	n;

	if (nb == 0)
		return (0);
	else if (nb == 1)
		return (1);
	n = 2;
	while (n < nb)
	{
		if (n * n == nb)
			return (n);
		n++;
	}
	return (0);
}
