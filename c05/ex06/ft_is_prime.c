int	ft_div(int nb)
{
	int	n;

	if (nb == 0 || nb == 1)
		return (1);
	n = 2;
	while (n < nb)
	{
		if (nb % n == 0)
			return (1);
		n++;
	}
	return (0);
}

int	ft_is_prime(int nb)
{
	if (ft_div(nb) == 1)
		return (0);
	return (1);
}
